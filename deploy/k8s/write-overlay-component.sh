#!/usr/bin/env bash
# Writes a Kustomize Component that pins the Hydra images of one build (spec section 3.4.4):
# Kustomize `images:` for the pods, and the ConfigMap hydra-images for HYDRA_SESSION_IMAGE and
# HYDRA_MCP_IMAGE (Kustomize `images:` does not change environment values). With --node-ip, the
# Component also sets the node IP of the API server egress rule (spec section 11.4). With
# --media-port-range, it also merges HYDRA_MEDIA_PORT_RANGE into the ConfigMap hydra-config of the
# overlay and patches the ports of the NetworkPolicy sessions-ingress-media (spec sections 4, 11.4),
# for a media port range that is not the default 52000-52099 (the overlay must have hydra-config).
#
# Callers: .github/workflows/release.yml (deploy/k8s/overlays/prod/images/kustomization.yaml) and
# scripts/dev-cluster.sh (deploy/k8s/overlays/dev/generated/kustomization.yaml).
#
# Usage: write-overlay-component.sh --out FILE --registry REGISTRY --tag TAG
#          --image NAME=sha256:HEX [--image NAME=sha256:HEX ...] [--node-ip IPV4]
#          [--media-port-range FIRST-LAST] [--source TEXT]
# NAME is hydra-gateway, hydra-session, hydra-mcp, or hydra-testsite. hydra-session and hydra-mcp
# are necessary. The output is the same for the same arguments. Works with bash 3.2 (macOS).
set -euo pipefail

WRITER_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=deploy/lib/cluster.sh
. "$WRITER_DIR/../lib/cluster.sh"

IMAGE_NAMES='hydra-gateway hydra-session hydra-mcp hydra-testsite'

die() {
  echo "write-overlay-component.sh: $*" >&2
  exit 2
}

out='' registry='' tag='' node_ip='' source_text='' media_range=''
images=()
while (($# > 0)); do
  case "$1" in
    --out | --registry | --tag | --image | --node-ip | --media-port-range | --source)
      (($# >= 2)) || die "$1 needs a value"
      case "$1" in
        --out) out="$2" ;;
        --registry) registry="$2" ;;
        --tag) tag="$2" ;;
        --image) images+=("$2") ;;
        --node-ip) node_ip="$2" ;;
        --media-port-range) media_range="$2" ;;
        --source) source_text="$2" ;;
      esac
      shift 2
      ;;
    *) die "unknown argument: $1" ;;
  esac
done

[[ -n "$out" ]] || die '--out is necessary'
[[ "$registry" =~ ^[a-z0-9.-]+(:[0-9]+)?(/[a-z0-9._-]+)*$ ]] || die "invalid --registry: '$registry'"
[[ "$tag" =~ ^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$ ]] || die "invalid --tag: '$tag'"
if [[ -n "$node_ip" ]]; then
  [[ "$node_ip" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] || die "invalid --node-ip: '$node_ip'"
fi

media_first='' media_last=''
if [[ -n "$media_range" ]]; then
  media_ports="$(hydra_media_ports "$media_range" 2>&1)" || die "invalid --media-port-range: $media_ports"
  media_first="${media_ports% *}"
  media_last="${media_ports#* }"
fi

(("${#images[@]}" > 0)) || die '--image is necessary'

# digest_of NAME : the digest given for NAME, or nothing
digest_of() {
  local arg
  for arg in "${images[@]}"; do
    if [[ "${arg%%=*}" == "$1" ]]; then
      echo "${arg#*=}"
      return
    fi
  done
}

for arg in "${images[@]}"; do
  name="${arg%%=*}"
  digest="${arg#*=}"
  [[ " $IMAGE_NAMES " == *" $name "* ]] || die "unknown image name: '$name'"
  [[ "$digest" =~ ^sha256:[0-9a-f]{64}$ ]] || die "invalid digest for $name: '$digest'"
done
[[ -n "$(digest_of hydra-session)" ]] || die '--image hydra-session=... is necessary'
[[ -n "$(digest_of hydra-mcp)" ]] || die '--image hydra-mcp=... is necessary'

{
  echo "# Generated by deploy/k8s/write-overlay-component.sh${source_text:+ ($source_text)}."
  echo '# Do not edit by hand.'
  echo 'apiVersion: kustomize.config.k8s.io/v1alpha1'
  echo 'kind: Component'
  echo 'images:'
  for name in $IMAGE_NAMES; do
    digest="$(digest_of "$name")"
    [[ -n "$digest" ]] || continue
    echo "  - name: $name"
    echo "    newName: $registry/$name"
    echo "    newTag: '$tag'"
    echo "    digest: $digest"
  done
  echo 'configMapGenerator:'
  echo '  - name: hydra-images'
  echo '    namespace: hydra'
  echo '    literals:'
  echo "      - HYDRA_SESSION_IMAGE=$registry/hydra-session:$tag@$(digest_of hydra-session)"
  echo "      - HYDRA_MCP_IMAGE=$registry/hydra-mcp:$tag@$(digest_of hydra-mcp)"
  if [[ -n "$media_range" ]]; then
    # The overlay generates hydra-config; this merges one more literal into it.
    echo '  - name: hydra-config'
    echo '    namespace: hydra'
    echo '    behavior: merge'
    echo '    literals:'
    echo "      - HYDRA_MEDIA_PORT_RANGE=$media_first-$media_last"
  fi
  if [[ -n "$node_ip" || -n "$media_range" ]]; then
    echo 'patches:'
  fi
  if [[ -n "$node_ip" ]]; then
    echo '  - target:'
    echo '      kind: NetworkPolicy'
    echo '      name: gateway-egress-apiserver'
    echo '    patch: |-'
    echo '      - op: replace'
    echo '        path: /spec/egress/0/to/0/ipBlock/cidr'
    echo "        value: $node_ip/32"
  fi
  if [[ -n "$media_range" ]]; then
    # sessions-ingress-media: ingress rule 0 has the UDP port entry 0 and the TCP port entry 1.
    echo '  - target:'
    echo '      kind: NetworkPolicy'
    echo '      name: sessions-ingress-media'
    echo '    patch: |-'
    for entry in 0 1; do
      echo '      - op: replace'
      echo "        path: /spec/ingress/0/ports/$entry/port"
      echo "        value: $media_first"
      echo '      - op: replace'
      echo "        path: /spec/ingress/0/ports/$entry/endPort"
      echo "        value: $media_last"
    done
  fi
} >"$out.tmp"
mv "$out.tmp" "$out"
